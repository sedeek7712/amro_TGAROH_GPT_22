import React from 'react';
import type { JournalEntry } from '../../types/erp';
import type { ResolvedDocumentHeader } from '../../utils/documentBranding';
import type { DocumentPaperSize } from '../../utils/printDocument';
import {
  DocumentAmountBanner,
  DocumentFooter,
  DocumentHeader,
  DocumentMetaGrid,
  DocumentSignatures,
} from './DocumentPrimitives';

interface JournalVoucherDocumentProps {
  entry: JournalEntry;
  meta: ResolvedDocumentHeader;
  paperSize: DocumentPaperSize;
}

const COST_CENTER_LABELS: Record<string, string> = {
  general: 'الإدارة العامة (CC-100)',
  pharmacy: 'الصيدلية (CC-101)',
  grocery: 'البقالة (CC-102)',
  bike_parts: 'قطع الدراجات (CC-103)',
  equipment_parts: 'قطع المعدات (CC-104)',
};

const REF_TYPE_LABELS: Record<string, string> = {
  INVOICE: 'فاتورة مبيعات / مشتريات',
  VOUCHER: 'سند قبض / صرف',
  MANUAL: 'قيد يومية يدوي / تسوية',
  AMANAT: 'حركة أمانات',
  ADVANCE_SETTLEMENT: 'تسوية رصيد مقدم',
  VOUCHER_REVERSAL: 'عكس سند مالي',
  INVENTORY: 'تسوية مخزنية',
};

export const JournalVoucherDocument: React.FC<JournalVoucherDocumentProps> = ({
  entry,
  meta,
  paperSize,
}) => {
  const isThermal = paperSize === '80mm' || paperSize === '58mm';
  const dec = meta.currency.decimalPlaces ?? 2;
  const sym = meta.currency.symbol;

  const totalDebit = entry.lines.reduce((s, l) => s + Number(l.debit || 0), 0);
  const totalCredit = entry.lines.reduce((s, l) => s + Number(l.credit || 0), 0);

  const statusLabel =
    entry.status === 'REVERSED'
      ? 'معكوس بقيد عكسي'
      : entry.status === 'DRAFT'
      ? 'مسودة'
      : 'مرحّل قطعي';
  const statusTone =
    entry.status === 'REVERSED'
      ? 'danger'
      : entry.status === 'DRAFT'
      ? 'warning'
      : 'success';

  return (
    <div dir="rtl" className="text-slate-900">
      <DocumentHeader
        meta={meta}
        paperSize={paperSize}
        documentTitle={entry.isAutoGenerated ? 'سند قيد محاسبي آلي' : 'سند قيد يومية / تسوية'}
        documentSubtitle={
          entry.referenceType ? REF_TYPE_LABELS[entry.referenceType] : 'دفتر اليومية العامة'
        }
        documentNumber={entry.entryNumber}
        documentDate={entry.date}
        statusLabel={statusLabel}
        statusTone={statusTone}
      />

      <DocumentMetaGrid
        paperSize={paperSize}
        columns={3}
        fields={[
          { label: 'رقم القيد', value: entry.entryNumber, mono: true },
          { label: 'تاريخ القيد', value: entry.date, mono: true },
          {
            label: 'مركز التكلفة',
            value: COST_CENTER_LABELS[entry.costCenterId] || entry.costCenterId,
          },
          {
            label: 'مصدر القيد',
            value: entry.referenceType ? REF_TYPE_LABELS[entry.referenceType] : 'يدوي',
          },
          { label: 'القيد المعكوس المرتبط', value: entry.reversedEntryId, mono: true },
          { label: 'البيان العام', value: entry.description, fullWidth: true },
        ]}
      />

      {entry.reversalReason && (
        <div className="mb-3 rounded-lg border border-rose-300 bg-rose-50 p-2.5 text-xs text-rose-900 doc-break-inside-avoid">
          <strong>سبب عكس القيد:</strong> {entry.reversalReason}
        </div>
      )}

      <div className="border border-slate-300 rounded-lg overflow-hidden mb-3">
        <table className={`w-full text-right ${isThermal ? 'text-[9.5px]' : 'text-xs'}`}>
          <thead>
            <tr className="bg-slate-900 text-white font-bold">
              <th className={isThermal ? 'py-1.5 px-1.5' : 'py-2 px-3'}>الحساب</th>
              <th className={isThermal ? 'py-1.5 px-1 text-center' : 'py-2 px-3 text-center'}>
                مدين
              </th>
              <th className={isThermal ? 'py-1.5 px-1 text-center' : 'py-2 px-3 text-center'}>
                دائن
              </th>
              {!isThermal && <th className="py-2 px-3">البيان الفرعي</th>}
            </tr>
          </thead>
          <tbody className="divide-y divide-slate-200">
            {entry.lines.map((line, idx) => (
              <tr key={line.id || idx} className={idx % 2 === 1 ? 'bg-slate-50/70' : 'bg-white'}>
                <td className={isThermal ? 'py-1.5 px-1.5' : 'py-2 px-3'}>
                  <div className="font-bold text-slate-900">
                    <span className="font-mono text-slate-500 ml-1">{line.accountCode}</span>
                    {line.accountName}
                  </div>
                  {isThermal && line.memo && (
                    <div className="text-[8.5px] text-slate-500">{line.memo}</div>
                  )}
                </td>
                <td
                  className={`text-center font-mono tabular-nums font-bold ${
                    isThermal ? 'py-1.5 px-1' : 'py-2 px-3'
                  }`}
                >
                  {Number(line.debit || 0) > 0 ? Number(line.debit).toFixed(dec) : '-'}
                </td>
                <td
                  className={`text-center font-mono tabular-nums font-bold ${
                    isThermal ? 'py-1.5 px-1' : 'py-2 px-3'
                  }`}
                >
                  {Number(line.credit || 0) > 0 ? Number(line.credit).toFixed(dec) : '-'}
                </td>
                {!isThermal && (
                  <td className="py-2 px-3 text-slate-600">{line.memo || '-'}</td>
                )}
              </tr>
            ))}
          </tbody>
          <tfoot>
            <tr className="border-t-2 border-slate-900 bg-slate-100 font-black">
              <td className={isThermal ? 'py-1.5 px-1.5' : 'py-2.5 px-3'}>الإجمالي المتوازن:</td>
              <td
                className={`text-center font-mono tabular-nums ${
                  isThermal ? 'py-1.5 px-1' : 'py-2.5 px-3'
                }`}
              >
                {totalDebit.toFixed(dec)}
              </td>
              <td
                className={`text-center font-mono tabular-nums ${
                  isThermal ? 'py-1.5 px-1' : 'py-2.5 px-3'
                }`}
              >
                {totalCredit.toFixed(dec)}
              </td>
              {!isThermal && <td className="py-2.5 px-3 text-emerald-800">مدين = دائن</td>}
            </tr>
          </tfoot>
        </table>
      </div>

      <DocumentAmountBanner
        label="إجمالي قيمة القيد المحاسبي"
        amount={totalDebit}
        currencySymbol={sym}
        currencyNameAr={meta.currency.nameAr}
        paperSize={paperSize}
      />

      <DocumentSignatures
        paperSize={paperSize}
        slots={[
          { roleLabel: 'أعدّ القيد', name: meta.issuerName },
          { roleLabel: 'المراجع المحاسبي' },
          { roleLabel: 'اعتماد المدير المالي' },
        ]}
      />

      <DocumentFooter
        meta={meta}
        paperSize={paperSize}
        referenceText={`JE: ${entry.entryNumber}`}
      />
    </div>
  );
};
