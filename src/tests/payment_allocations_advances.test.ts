  test('Customer FIFO across 3 invoices + Overpayment -> 2103 + POS Advance Settlement + Reversal Guard', async () => {
    const customer: Party = {
      id: 'cust-fifo-1',
      type: 'CUSTOMER',
      nameAr: 'عميل التجزئة المتقدم',
      phone: '777100200',
      balance: 0,
      advanceBalance: 0,
    };
    await dexieDataService.savePartyAtomic(customer);

    const makeCreditSale = async (id: string, date: string, qty: number, dueDate?: string) => {
      const total = qty * 1000;
      const res = await dexieDataService.createSalesInvoiceAtomic({
        invoice: {
          id,
          invoiceNumber: '',
          type: 'SALE',
          activityId: 'grocery',
          branchId: 'branch_main',
          partyId: customer.id,
          partyName: customer.nameAr,
          date,
          dueDate,
          items: [
            {
              id: `${id}-l1`,
              productId: prod.id,
              productName: prod.nameAr,
              productCode: prod.code,
              unit: prod.unit,
              quantity: qty,
              unitPrice: 1000,
              discount: 0,
              total,
            },
          ],
          subtotal: total,
          discount: 0,
          tax: 0,
          total,
          paidAmount: 0,
          paymentMethod: 'CREDIT',
          cashBoxId: 'cb-1',
        },
        totalCogs: qty * 500,
        stockDeductions: [{ productId: prod.id, quantity: qty }],
      });
      return res.invoice;
    };

    const inv1 = await makeCreditSale('inv-f1', '2026-11-01', 50); // 50,000
    const inv2 = await makeCreditSale('inv-f2', '2026-11-02', 40); // 40,000
    const inv3 = await makeCreditSale('inv-f3', '2026-11-03', 30); // 30,000
    assert.equal((await db.parties.get(customer.id))?.balance, 120000);

    // Pay 100,000 -> FIFO allocates 50,000 (inv1), 40,000 (inv2), 10,000 (inv3)
    const rct1 = await dexieDataService.createCashVoucherAtomic({
      voucher: {
        id: 'v-fifo-1',
        voucherNumber: '',
        type: 'RECEIPT',
        voucherMode: 'CUSTOMER_RECEIPT',
        date: '2026-11-05',
        amount: 100000,
        cashBoxId: 'cb-1',
        branchId: 'branch_main',
        partyId: customer.id,
        partyType: 'CUSTOMER',
        partyName: customer.nameAr,
        accountCode: '1103',
        paymentMethod: 'CASH',
        description: 'سداد دفعة 100 ألف FIFO',
        costCenterId: 'general',
        status: 'POSTED',
      },
    });

    assert.equal(rct1.voucher.appliedToDebtAmount, 100000);
    assert.equal(rct1.voucher.advanceAmount, 0);
    assert.equal((await db.invoices.get(inv1.id))?.paidAmount, 50000);
    assert.equal((await db.invoices.get(inv2.id))?.paidAmount, 40000);
    assert.equal((await db.invoices.get(inv3.id))?.paidAmount, 10000);
    assert.equal((await db.parties.get(customer.id))?.balance, 20000);

    // Customer pays 50,000 -> 20,000 settles inv3 + 30,000 goes to Advance 2103!
    const rctOver = await dexieDataService.createCashVoucherAtomic({
      voucher: {
        id: 'v-over-1',
        voucherNumber: '',
        type: 'RECEIPT',
        voucherMode: 'CUSTOMER_RECEIPT',
        date: '2026-11-06',
        amount: 50000,
        cashBoxId: 'cb-1',
        branchId: 'branch_main',
        partyId: customer.id,
        partyType: 'CUSTOMER',
        partyName: customer.nameAr,
        accountCode: '1103',
        paymentMethod: 'BANK_TRANSFER',
        externalRef: 'TRX-8899',
        description: 'دفعة زائدة تسجل كرصيد مقدم',
        costCenterId: 'general',
        status: 'POSTED',
      },
    });

    assert.equal(rctOver.voucher.appliedToDebtAmount, 20000);
    assert.equal(rctOver.voucher.advanceAmount, 30000);
    assert.equal((await db.invoices.get(inv3.id))?.paidAmount, 30000);
    assert.equal((await db.parties.get(customer.id))?.balance, 0);
    assert.equal((await db.parties.get(customer.id))?.advanceBalance, 30000);
    assert.equal((await db.accounts.get('2103'))?.balance, 30000);

    const cashBeforeAdvanceSale = (await db.cashBoxes.get('cb-1'))!.balance;

    // New POS invoice 25,000: apply 15,000 from advance + 10,000 cash -> Dr 2103 / Cr 1103 standalone JE!
    const advSale = await dexieDataService.createSalesInvoiceAtomic({
      invoice: {
        id: 'inv-adv-use',
        invoiceNumber: '',
        type: 'SALE',
        activityId: 'grocery',
        branchId: 'branch_main',
        partyId: customer.id,
        partyName: customer.nameAr,
        date: '2026-11-07',
        items: [
          {
            id: 'adv-l1',
            productId: prod.id,
            productName: prod.nameAr,
            productCode: prod.code,
            unit: prod.unit,
            quantity: 25,
            unitPrice: 1000,
            discount: 0,
            total: 25000,
          },
        ],
        subtotal: 25000,
        discount: 0,
        tax: 0,
        total: 25000,
        paidAmount: 10000, // ONLY cash paid
        paymentMethod: 'CASH',
        cashBoxId: 'cb-1',
      },
      totalCogs: 12500,
      stockDeductions: [{ productId: prod.id, quantity: 25 }],
      applyAdvanceAmount: 15000,
    });

    assert.ok(advSale.advanceJournalEntry, 'Must create standalone ADVANCE_SETTLEMENT journal entry');
    assert.equal(advSale.advanceJournalEntry?.referenceType, 'ADVANCE_SETTLEMENT');
    assert.equal(advSale.invoice.paidAmount, 25000);
    assert.equal(advSale.invoice.advanceAppliedAmount, 15000);
    assert.equal((await db.cashBoxes.get('cb-1'))?.balance, cashBeforeAdvanceSale + 10000);
    assert.equal((await db.parties.get(customer.id))?.advanceBalance, 15000);
    assert.equal((await db.accounts.get('2103'))?.balance, 15000);

    // Reversal of rctOver MUST BE BLOCKED because 15,000 of the 30,000 advance was spent!
    await assert.rejects(
      () =>
        dexieDataService.reverseCashVoucherAtomic({
          voucherId: rctOver.voucher.id,
          reversalReason: 'محاولة عكس بعد صرف الرصيد المقدم',
        }),
      /قد استُخدم بالفعل/
    );

    // Verify reconciliation & Balance Sheet match cleanly
    const allAccounts = await db.accounts.toArray();
    const allEntries = await db.journalEntries.toArray();
    const allParties = await db.parties.toArray();

    const bs = accounting.getBalanceSheet({ accounts: allAccounts, entries: allEntries });
    assert.equal(bs.isBalanced, true, `Balance sheet must balance (diff=${bs.diff})`);

    const rec = accounting.getControlReconciliation({ parties: allParties, accounts: allAccounts });
    for (const row of rec) {
      assert.equal(row.isMatched, true, `Control reconciliation failed for ${row.controlAccountCode}: diff=${row.diff}`);
    }
  });

  test('Manual override RBAC + AllocationAudit + DRAFT lifecycle + Reversal when unspent', async () => {
    const customer: Party = {
      id: 'cust-ovr-1',
      type: 'CUSTOMER',
      nameAr: 'عميل تخصيص يدوي',
      phone: '777300400',
      balance: 0,
      advanceBalance: 0,
    };
    await dexieDataService.savePartyAtomic(customer);

    const makeSale = async (id: string, date: string, total: number) =>
      (
        await dexieDataService.createSalesInvoiceAtomic({
          invoice: {
            id,
            invoiceNumber: '',
            type: 'SALE',
            activityId: 'grocery',
            branchId: 'branch_main',
            partyId: customer.id,
            partyName: customer.nameAr,
            date,
            items: [
              {
                id: `${id}-l`,
                productId: prod.id,
                productName: prod.nameAr,
                productCode: prod.code,
                unit: prod.unit,
                quantity: total / 1000,
                unitPrice: 1000,
                discount: 0,
                total,
              },
            ],
            subtotal: total,
            discount: 0,
            tax: 0,
            total,
            paidAmount: 0,
            paymentMethod: 'CREDIT',
            cashBoxId: 'cb-1',
          },
          totalCogs: (total / 1000) * 500,
          stockDeductions: [{ productId: prod.id, quantity: total / 1000 }],
        })
      ).invoice;

    const s1 = await makeSale('s-ovr-1', '2026-11-01', 10000);
    const s2 = await makeSale('s-ovr-2', '2026-11-02', 10000);

    // Switch to ACCOUNTANT -> manual override must be blocked!
    await loginAs(accountantUser, 'Accountant#2026!');
    await assert.rejects(
      () =>
        dexieDataService.createCashVoucherAtomic({
          voucher: {
            id: 'v-acc-override-fail',
            voucherNumber: '',
            type: 'RECEIPT',
            voucherMode: 'CUSTOMER_RECEIPT',
            date: '2026-11-05',
            amount: 5000,
            cashBoxId: 'cb-1',
            branchId: 'branch_main',
            partyId: customer.id,
            partyType: 'CUSTOMER',
            partyName: customer.nameAr,
            accountCode: '1103',
            description: 'تجاوز غير مصرح به',
            costCenterId: 'general',
          },
          manualAllocations: [{ invoiceId: s2.id, allocatedAmount: 5000 }],
          overrideReason: 'اختبار صلاحية المحاسب',
        }),
      /payment:allocation:override/
    );

    // Switch back to ADMIN -> DRAFT voucher -> post via postDraftCashVoucherAtomic with override
    await loginAs(adminUser, 'Admin#Alloc2026!');
    const draftRes = await dexieDataService.createCashVoucherAtomic({
      voucher: {
        id: 'v-draft-ovr',
        voucherNumber: '',
        type: 'RECEIPT',
        voucherMode: 'CUSTOMER_RECEIPT',
        date: '2026-11-05',
        amount: 5000,
        cashBoxId: 'cb-1',
        branchId: 'branch_main',
        partyId: customer.id,
        partyType: 'CUSTOMER',
        partyName: customer.nameAr,
        accountCode: '1103',
        description: 'مسودة تحصيل بتخصيص يدوي',
        costCenterId: 'general',
        status: 'DRAFT',
      },
    });
    assert.equal(draftRes.voucher.status, 'DRAFT');
    assert.equal((await db.invoices.get(s2.id))?.paidAmount, 0);

    const postedRes = await dexieDataService.postDraftCashVoucherAtomic({
      voucherId: draftRes.voucher.id,
      manualAllocations: [{ invoiceId: s2.id, allocatedAmount: 5000 }],
      overrideReason: 'اعتماد تخصيص الفاتورة الثانية أولاً',
    });

    assert.equal(postedRes.voucher.status, 'POSTED');
    assert.equal((await db.invoices.get(s1.id))?.paidAmount, 0);
    assert.equal((await db.invoices.get(s2.id))?.paidAmount, 5000);

    const audits = await dexieDataService.getAllocationAudits(postedRes.voucher.id);
    assert.equal(audits.length, 1);
    assert.equal(audits[0].reason, 'اعتماد تخصيص الفاتورة الثانية أولاً');
    assert.equal(audits[0].previousAllocations[0].invoiceId, s1.id);
    assert.equal(audits[0].newAllocations[0].invoiceId, s2.id);

    // Reject cancelling a POSTED voucher
    await assert.rejects(
      () =>
        dexieDataService.cancelCashVoucherAtomic({
          voucherId: postedRes.voucher.id,
          reason: 'محاولة إلغاء سند مرحل',
        }),
      /إلغاء أو حذف سند مالي مرحّل/
    );

    // Reversal of POSTED voucher restores invoice & party balance cleanly
    const revRes = await dexieDataService.reverseCashVoucherAtomic({
      voucherId: postedRes.voucher.id,
      reversalReason: 'خطأ في العميل المستلم منه',
    });
    assert.equal(revRes.voucher.status, 'REVERSED');
    assert.equal((await db.invoices.get(s2.id))?.paidAmount, 0);
    assert.equal((await db.parties.get(customer.id))?.balance, 20000);

    // Test cancelling a DRAFT voucher succeeds cleanly
    const draftToCancel = await dexieDataService.createCashVoucherAtomic({
      voucher: {
        id: 'v-draft-cancel',
        voucherNumber: '',
        type: 'PAYMENT',
        voucherMode: 'GENERAL',
        date: '2026-11-05',
        amount: 100,
        cashBoxId: 'cb-1',
        branchId: 'branch_main',
        partyName: 'صيانة',
        accountCode: '5204',
        description: 'مسودة مصروف ستُلغى',
        costCenterId: 'general',
        status: 'DRAFT',
      },
    });
    const cancelled = await dexieDataService.cancelCashVoucherAtomic({
      voucherId: draftToCancel.voucher.id,
      reason: 'تم الاستغناء عن السند',
    });
    assert.equal(cancelled.status, 'CANCELLED');
  });

