async function assertDexieTrialBalanceZero() {
  const entries = await db.journalEntries.toArray();
  let debit = 0;
  let credit = 0;
  for (const e of entries) {
    for (const l of e.lines || []) {
      debit += Number(l.debit || 0);
      credit += Number(l.credit || 0);
    }
  }
  assert.ok(debit > 0, 'Expected non-zero posted journal entries');
  assert.ok(Math.abs(debit - credit) < 0.001, `GL imbalance: debit=${debit} vs credit=${credit}`);
}

