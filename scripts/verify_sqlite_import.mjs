  assert.equal(preview.financialTotals.journalDebit, '125.500000');
  assert.equal(preview.financialTotals.journalCredit, '125.500000');

  const imported = await importLegacyBackup(runtime.database, runtime.backupDirectory, raw);
  assert.equal(imported.success, true);
  assert.equal(imported.rowCounts.productBatches, 1);
  assert.equal(imported.rowCounts.invoiceItems, 1);
  assert.equal(imported.financialTotals.invoiceTotal, '125.500000');
  assert.equal(imported.financialTotals.accountBalances, '1100.000000');

  const db = runtime.database;
  assert.equal(db.prepare("SELECT COUNT(*) AS count FROM journal_entry_lines").get().count, 2);
  assert.equal(db.prepare("SELECT COUNT(*) AS count FROM invoice_stock_deductions").get().count, 1);
  assert.equal(db.prepare("SELECT COUNT(*) AS count FROM legacy_imports").get().count, 1);

  const auth = new DesktopAuthenticationService(db);
  const login = auth.authenticate({username:'admin',password:adminPassword});
  assert.equal(login.success, true);
  assert.equal(login.user.role, 'ADMIN');

  await assert.rejects(
    importLegacyBackup(db, runtime.backupDirectory, raw),
    /تحتوي بيانات فعلية/
  );

  const tampered = JSON.parse(raw);
  tampered.data.invoices[0].total = 999;
  await assert.rejects(
    importLegacyBackup(db, runtime.backupDirectory, JSON.stringify(tampered)),
    /Checksum/
  );

  assert.equal(db.prepare('PRAGMA integrity_check').get().integrity_check, 'ok');
  runtime.close();
  console.log('PASS: legacy backup preview/import, child rows, batch retention, financial totals, auth and duplicate protection');
