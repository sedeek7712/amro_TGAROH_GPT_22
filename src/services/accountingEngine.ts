  // توليد رقم قيد تسلسلي جديد
  public generateEntryNumber(): string {
    const entries = storage.getJournalEntries();
    const count = entries.length + 1;
    return `JV-${new Date().getFullYear()}-${String(count).padStart(5, '0')}`;
  }

  // التحقق من صحة وتوازن القيد المحاسبي (المدين = الدائن دائماً)
  public validateJournalEntry(lines: JournalEntryLine[]): { isValid: boolean; error?: string } {
    if (!lines || lines.length < 2) {
      return { isValid: false, error: 'يجب أن يحتوي القيد على طرفين على الأقل (طرف مدين وطرف دائن).' };
    }

    for (const line of lines) {
      const debit = Number(line.debit) || 0;
      const credit = Number(line.credit) || 0;
      if (debit < 0 || credit < 0) {
        return { isValid: false, error: 'لا يجوز أن تحتوي أسطر القيد على قيم سالبة.' };
      }
      if (debit > 0 && credit > 0) {
        return { isValid: false, error: 'لا يجوز أن يحمل سطر واحد مديناً ودائناً في آن واحد.' };
      }
    }

    const totalDebit = roundMoney(lines.reduce((sum, line) => sum + (Number(line.debit) || 0), 0));
    const totalCredit = roundMoney(lines.reduce((sum, line) => sum + (Number(line.credit) || 0), 0));

    const diff = Math.abs(totalDebit - totalCredit);
    if (diff > 0.009) {
      return {
        isValid: false,
        error: `القيد غير متوازن! إجمالي المدين (${totalDebit.toFixed(2)}) لا يساوي إجمالي الدائن (${totalCredit.toFixed(2)}). فارق: ${diff.toFixed(2)}`,
      };
    }

    if (totalDebit <= 0) {
      return { isValid: false, error: 'مبلغ القيد يجب أن يكون أكبر من الصفر.' };
    }

    return { isValid: true };
  }

  // ترحيل قيد يومية يدوي (مرحل قطعي POSTED)
  public postManualJournalEntry(
    date: string,
    description: string,
    lines: JournalEntryLine[],
    costCenterId: CostCenterId = 'general'
  ): { success: boolean; entryNumber?: string; error?: string } {
    const validation = this.validateJournalEntry(lines);
    if (!validation.isValid) {
      return { success: false, error: validation.error };
    }

    const entryNumber = this.generateEntryNumber();
    const newEntry: JournalEntry = {
      id: storage.generateUUID(),
      entryNumber,
      date,
      description,
      costCenterId,
      lines,
      status: 'POSTED',
      referenceType: 'MANUAL',
      isAutoGenerated: false,
    };

    // تطبيق أثر القيد على أرصدة الحسابات وفق طبيعة كل حساب
    const accounts = storage.getAccounts();
    lines.forEach((line) => {
      const acc = accounts.find((a) => a.code === line.accountCode);
      const debit = Number(line.debit) || 0;
      const credit = Number(line.credit) || 0;
      const netDelta =
        acc && (acc.type === 'LIABILITY' || acc.type === 'EQUITY' || acc.type === 'REVENUE')
          ? credit - debit
          : debit - credit;
      storage.updateAccountBalance(line.accountCode, netDelta);
    });

    storage.addJournalEntry(newEntry);
    return { success: true, entryNumber };
  }

  // ترحيل قيد فاتورة مبيعات تلقائياً للأنشطة التجارية الأربعة
  public postSaleInvoice(invoice: Invoice, totalCostOfGoods: number = 0): string {
    const entryNumber = this.generateEntryNumber();
    const lines: JournalEntryLine[] = [];

    // الحسابات المرتبطة بالأنشطة التجارية الأربعة
    const activityRevenueAccounts: Record<CommercialActivityId, string> = {
      pharmacy: '4101',
      grocery: '4102',
      bike_parts: '4103',
      equipment_parts: '4104',
    };

    const activityInventoryAccounts: Record<CommercialActivityId, string> = {
      pharmacy: '11041',
      grocery: '11042',
      bike_parts: '11043',
      equipment_parts: '11044',
    };

    const activityCogsAccounts: Record<CommercialActivityId, string> = {
      pharmacy: '5101',
      grocery: '5102',
      bike_parts: '5103',
      equipment_parts: '5104',
    };

    const revenueAccountCode = activityRevenueAccounts[invoice.activityId] || '4101';
    const revenueAccount = storage.getAccounts().find((a) => a.code === revenueAccountCode);

    // 1. الطرف المدين: النقدية بالصندوق أو ذمة العميل الآجل
    if (invoice.paidAmount > 0) {
      const cashBox = storage.getCashBoxes().find((b) => b.id === invoice.cashBoxId) || storage.getCashBoxes()[0];
      lines.push({
        id: storage.generateUUID(),
        accountCode: cashBox.accountCode,
        accountName: cashBox.nameAr,
        debit: invoice.paidAmount,
        credit: 0,
        costCenterId: invoice.activityId,
        memo: `سداد نقدي فاتورة مبيعات ${invoice.invoiceNumber}`,
      });
      storage.updateCashBoxBalance(cashBox.id, invoice.paidAmount);
      storage.updateAccountBalance(cashBox.accountCode, invoice.paidAmount);
    }

    const unpaidAmount = Number((invoice.total - invoice.paidAmount).toFixed(2));
    if (unpaidAmount > 0) {
      lines.push({
        id: storage.generateUUID(),
        accountCode: '1103',
        accountName: 'العملاء والمدينون - ' + invoice.partyName,
        debit: unpaidAmount,
        credit: 0,
        costCenterId: invoice.activityId,
        memo: `مبيعات آجلة فاتورة ${invoice.invoiceNumber}`,
      });
      storage.updateAccountBalance('1103', unpaidAmount);
      if (invoice.partyId) {
        storage.updatePartyBalance(invoice.partyId, unpaidAmount);
      }
    }

    // 2. الطرف الدائن: إيراد المبيعات
    lines.push({
      id: storage.generateUUID(),
      accountCode: revenueAccountCode,
      accountName: revenueAccount?.nameAr || 'إيرادات المبيعات',
      debit: 0,
      credit: invoice.total,
      costCenterId: invoice.activityId,
      memo: `إيراد مبيعات فاتورة ${invoice.invoiceNumber}`,
    });
    storage.updateAccountBalance(revenueAccountCode, invoice.total);

    // 3. قيد تكلفة البضاعة المباعة والمخزون (Perpetual Inventory)
    if (totalCostOfGoods > 0) {
      const cogsCode = activityCogsAccounts[invoice.activityId];
      const invCode = activityInventoryAccounts[invoice.activityId];
      const cogsAcc = storage.getAccounts().find((a) => a.code === cogsCode);
      const invAcc = storage.getAccounts().find((a) => a.code === invCode);

      // مدين: تكلفة المبيعات
      lines.push({
        id: storage.generateUUID(),
        accountCode: cogsCode,
        accountName: cogsAcc?.nameAr || 'تكلفة المبيعات',
        debit: totalCostOfGoods,
        credit: 0,
        costCenterId: invoice.activityId,
        memo: `تكلفة بضاعة مباعة فاتورة ${invoice.invoiceNumber}`,
      });
      storage.updateAccountBalance(cogsCode, totalCostOfGoods);

      // دائن: المخزون التجاري
      lines.push({
        id: storage.generateUUID(),
        accountCode: invCode,
        accountName: invAcc?.nameAr || 'المخزون السلعي',
        debit: 0,
        credit: totalCostOfGoods,
        costCenterId: invoice.activityId,
        memo: `صرف مخزون مباع فاتورة ${invoice.invoiceNumber}`,
      });
      storage.updateAccountBalance(invCode, -totalCostOfGoods);
    }

    const newEntry: JournalEntry = {
      id: storage.generateUUID(),
      entryNumber,
      date: invoice.date,
      description: `فاتورة مبيعات ${invoice.invoiceNumber} - ${invoice.partyName}`,
      costCenterId: invoice.activityId,
      lines,
      status: 'POSTED',
      referenceType: 'INVOICE',
      referenceId: invoice.id,
      isAutoGenerated: true,
    };

    storage.addJournalEntry(newEntry);
    return newEntry.id;
  }

