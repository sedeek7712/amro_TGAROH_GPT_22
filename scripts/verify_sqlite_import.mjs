  const runtime = await openErpDatabase({ userDataPath });
  const { backup, adminPassword } = fixture();
  const raw = JSON.stringify(backup);

  const preview = previewLegacyBackup(raw);
  assert.equal(preview.sourceSystem, 'multi_activity_erp');
  assert.equal(preview.rowCounts.invoices, 1);
