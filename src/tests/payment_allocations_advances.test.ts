    assert.equal((await db.parties.get(supplier.id))?.balance, 0);
    assert.equal((await db.parties.get(supplier.id))?.advanceBalance, 2000);
    assert.equal((await db.accounts.get('1105'))?.balance, 2000);
    assert.equal((await db.accounts.get('2101'))?.balance, 0);
